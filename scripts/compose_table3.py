"""Compose the paper's Table 3 (tab:injection) from its two generators.

Upper block: the rows that scripts/analyze_paper.py writes to outputs/tables/coldstart_results.tex.
Lower block: the rows that scripts/analyze_alternatives.py writes to table3_lower_rows.tex (outputs/).
Run it after both; it rewrites outputs/tables/coldstart_results.tex. It is idempotent: an existing lower block is
dropped and rebuilt.

    python -B scripts/compose_table3.py [--check] [--rows FILE]

--check compares the composed table with the published one (data/results/tables/coldstart_results.tex) instead of
writing, and exits non-zero on any difference. Run scripts/reproduce.py first to generate both blocks.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "outputs/tables/coldstart_results.tex"
PUBLISHED = ROOT / "data/results/tables/coldstart_results.tex"
ROWS = ROOT / "outputs/table3_lower_rows.tex"

# label in table3_lower_rows.tex -> paper label, in the paper's row order
LOWER = [
    ("LUFFY-style mixed-policy", "LUFFY-style mixed policy"),
    ("Self-replay (own successes, cap 100)", "Self-replay (own successes)"),
    ("ReLIFT-style interleaved SFT", "ReLIFT-style interleaved SFT"),
    ("No injection, total-cost budget 88.8k", r"No injection, 88.8k budget$\ddagger$"),
]

HEADER = r"""% Main rows: generated by scripts/analyze_paper.py.
% Alternatives block: from outputs/table3_lower_rows.tex (scripts/analyze_alternatives.py); values and
% intervals re-checked against outputs/table3_per_task.csv.
\begin{table*}[t]
\centering\footnotesize
\caption{Cold-start results, seeds 601/602/603; test pass@1 as mean $\pm$ sample SD ($n=8$ telecom, $n=4$ math). $\Delta$: paired 95\% task-bootstrap interval, conditional on these policies, against no injection (upper block) or against real-source injection (lower block: alternatives on the weak telecom start, same recipe). Target calls (k) and exposures (stored successes used) follow seed order; source collection is charged to no arm. $\dagger$: conservative failed-shard charge (\cref{sec:injection-setup}). $\ddagger$: seed 602 stopped at 57.0k calls without a test evaluation; mean over seeds 601 and 603.}
\label{tab:injection}
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}llrrrrr@{}}
\toprule
Env & Arm & pass@1 & pass@$n$ & $\Delta$ [95\% CI], pp & Target calls (k) & Exposures \\
\midrule
"""
FOOTER = "\\bottomrule\n\\end{tabular}\n\\end{table*}\n"


def upper_rows(text):
    lines = text.splitlines()
    start = next(i for i, line in enumerate(lines) if line.strip() == r"\midrule") + 1
    rows = []
    for line in lines[start:]:
        if line.strip() in (r"\midrule", r"\bottomrule"):
            break
        if line.startswith(("Telecom &", "Math &")):
            rows.append(line)
    if len(rows) != 4:
        raise ValueError(f"expected 4 upper rows in {TABLE}, found {len(rows)}")
    return rows


def signed(x):
    return x.replace("-", "$-$")


def lower_rows(text):
    found = {}
    for line in text.splitlines():
        if not line.startswith("Telecom &"):
            continue
        cells = [c.strip() for c in line.rstrip("\\ ").split(" & ")]
        found[cells[1]] = cells
    rows = []
    for label, paper_label in LOWER:
        if label not in found:
            raise ValueError(f"missing lower-block row: {label}")
        env, _, p1, pn, delta, calls, exposures = found[label]
        calls = calls.replace(r"$^\ddagger$", "")
        rows.append(" & ".join([env, paper_label, p1, pn, signed(delta), calls, exposures]) + r" \\")
    return rows


def compose(upper_src=TABLE):
    upper = upper_rows(upper_src.read_text())
    lower = lower_rows(ROWS.read_text())
    return HEADER + "\n".join(upper) + "\n\\midrule\n" + "\n".join(lower) + "\n" + FOOTER


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with the published table instead of writing")
    ap.add_argument("--rows", type=Path, default=ROWS, help=f"lower-block rows (default {ROWS.relative_to(ROOT)})")
    args = ap.parse_args()
    ROWS = args.rows
    table = compose(TABLE)
    if args.check:
        same = PUBLISHED.read_text() == table
        print("Table 3 matches the published table" if same else "Table 3 differs from the published table")
        sys.exit(0 if same else 1)
    TABLE.write_text(table)
    print("wrote", TABLE.relative_to(ROOT))
